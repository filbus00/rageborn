-- Packs a font's glyphs into one white atlas, a pixel apart, and writes it with its JSON.
local function write(name, glyphs, cell, ascent, space)
  local chars = {}
  for ch in pairs(glyphs) do chars[#chars + 1] = ch end
  table.sort(chars)
  local W, x, y, rowH = 256, 1, 1, 0
  local placed = {}
  for _, ch in ipairs(chars) do
    local rows = glyphs[ch]
    local w = #rows[1]
    if x + w + 1 > W then x, y = 1, y + cell + 1 end
    placed[#placed + 1] = { ch = ch, x = x, y = y, w = w, rows = rows }
    x = x + w + 1
  end
  local H = y + cell + 1
  local atlas = Image(W, H, ColorMode.RGB)
  atlas:clear(app.pixelColor.rgba(0, 0, 0, 0))
  local white = app.pixelColor.rgba(255, 255, 255, 255)
  local json = {}
  for _, p in ipairs(placed) do
    for r, row in ipairs(p.rows) do
      for c = 1, #row do
        if row:sub(c, c) == "#" then atlas:drawPixel(p.x + c - 1, p.y + r - 1, white) end
      end
    end
    -- Every glyph takes its whole cell (the rows past its own are clear), its top at the ascent.
    local code = utf8.codepoint(p.ch)
    json[#json + 1] = string.format('{"code":%d,"x":%d,"y":%d,"w":%d,"advance":%d}', code, p.x, p.y, p.w, p.w + 1)
  end
  atlas:saveAs(out .. "/font_" .. name .. ".png")
  local f = io.open(out .. "/font_" .. name .. ".json", "w")
  f:write(string.format('{"cell":%d,"ascent":%d,"space":%d,"atlasHeight":%d,"glyphs":[\n%s\n]}\n', cell, ascent, space, H,
    table.concat(json, ",\n")))
  f:close()
  print("REPORT font " .. name .. " " .. #placed .. " glyphs, atlas " .. W .. " x " .. H)
end

